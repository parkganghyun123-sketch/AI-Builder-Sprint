"""
서명 위치 상수 — 단일 출처(single source of truth)

이 값들은 세 곳에서 쓰인다.
  - backend/app/signing/modusign.py   실제 서명 요청
  - spikes/modusign_spike.py          수동 테스트 발송
  - spikes/preview_sign_box.py        발송 없이 위치 미리보기

예전에는 각 파일이 값을 복사해 두었고, 그 결과 서로 어긋나
"스파이크로 보낼 때와 API로 보낼 때 서명 위치가 다른" 문제가 있었다.
(spike 0.10 / -0.012  vs  backend -0.05 / -0.72)

⚠️ 이 모듈은 표준 라이브러리 외에 아무것도 import 하지 않는다.
   스파이크 스크립트가 httpx·pydantic 같은 무거운 의존성 없이
   가져다 쓸 수 있어야 하기 때문이다. 여기에 로직을 넣지 말 것.
"""

# ------------------------------------------------------------ anchor
#
# 설계 원칙 2가지:
#   1. 참여자별로 유일해야 한다.
#      표준양식 원본은 "(서명)"으로만 표기하지만, 같은 텍스트가 2번 나오면
#      모두싸인이 매칭 개수만큼 필드를 만들어 근로자·사업주를 구분할 수 없다.
#   2. 서명이 들어갈 위치 바로 그 자리에 있어야 한다.
#      멀리 떨어진 텍스트('성명' 등)에서 offset으로 밀면 오차가 크게 벌어진다.
#
# ⚠️ backend/app/pdf/templates/employment_contract.html 의
#    .sign-anchor 라벨 문구와 정확히 일치해야 한다.
ANCHOR_EMPLOYER = "(사업주 서명)"
ANCHOR_WORKER = "(근로자 서명)"

# --------------------------------------------------- 서명 박스 크기
# 문서 너비·높이 대비 비율
SIGN_BOX_W = 0.14
SIGN_BOX_H = 0.045

# ------------------------------------------------------------ offset
#
# anchor 라벨 "위에 겹치도록" 박스를 놓는다.
#
# --- 1단계: 기하학적 계산 ---
#   A4 595 x 842pt 기준 라벨 '(근로자 서명)' 실측
#     x 290.7-337.7pt → 정규화 0.489-0.568 (폭 0.079)
#     y 182.5-193.3pt → 정규화 0.217-0.230 (높이 0.013)
#   박스를 라벨 중앙에 맞추려면
#     offset_x = -(SIGN_BOX_W - 0.079) / 2 = -0.031
#     offset_y = -(SIGN_BOX_H - 0.013) / 2 = -0.016
#
# --- 2단계: 실측 보정 ---
#   위 값으로 실제 발송(문서 9d262170-8a73-11f1)한 결과를 측정하니
#   모두싸인이 놓은 박스가 계산 위치와 달랐다.
#     X  오차 -0.021  (측정 오차 범위, 모델 유효)
#     Y  오차 +0.225  ← 페이지 높이의 22.5%만큼 아래로 밀림
#
#   즉 모두싸인은 anchor의 세로 좌표를 우리와 다른 기준으로 잡는다.
#   기준점이 API 문서에 명시돼 있지 않아 원인은 규명하지 못했고,
#   실측 오차를 그대로 빼는 방식으로 보정했다.
#     offset_x = -0.031 + 0.021 = -0.010
#     offset_y = -0.016 - 0.230 = -0.246
#
# ⚠️ 이 값은 이론이 아니라 실측 보정값이다. 따라서
#    - employment_contract.html 레이아웃을 바꾸면 다시 실측해야 한다
#    - spikes/preview_sign_box.py 의 미리보기는 X만 신뢰할 수 있다
#      (Y는 위 보정이 들어가 있지 않아 실제보다 위로 그려진다)
#    - 모두싸인이 anchor 처리 방식을 바꾸면 어긋날 수 있다
#
# ⚠️ 측정 정밀도는 정규화 좌표 기준 약 ±0.01 (A4에서 8pt)이다.
#    한 번 더 발송해 확인한 뒤 필요하면 미세조정할 것.
SIGN_OFFSET_X = -0.010
SIGN_OFFSET_Y = -0.246

# 모두싸인이 세로로 밀어놓는 양 (실측).
# offset 계산에 이미 반영돼 있고, 미리보기 도구가
# "실제로 놓일 자리"를 그리는 데 쓴다.
MODUSIGN_Y_DRIFT = 0.230
